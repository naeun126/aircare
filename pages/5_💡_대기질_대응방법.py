import streamlit as st


st.title("💡 대기질 대응 방법")

st.write(
    "현재 대기질 상태를 바탕으로 오염물질별 대응 방법을 확인할 수 있습니다."
)

st.info(
    "아래 내용은 AirCare 프로젝트에서 대기질 상태에 따라 "
    "일상적인 대응 방법을 안내하기 위한 참고 정보입니다."
)

st.divider()


# -------------------------
# 대기오염물질별 대응 방법
# -------------------------

st.subheader("🌫️ PM10")

st.write(
    """
    PM10 농도가 높게 나타나는 경우에는 외부에서 유입되는
    미세먼지를 줄이고 실내 공기질을 관리하는 것이 중요합니다.

    • 외출 시 미세먼지 농도를 확인합니다.
    • 외부 공기가 좋지 않은 시간에는 불필요한 외출을 줄입니다.
    • 실내에서는 공기청정기나 환기장치를 적절히 활용합니다.
    • 청소할 때 먼지가 다시 날리지 않도록 주의합니다.
    """
)


st.subheader("🌫️ PM2.5")

st.write(
    """
    PM2.5는 입자가 매우 작은 미세먼지입니다.

    • 실외 대기질을 확인한 후 환기 시간을 조절합니다.
    • 미세먼지가 높은 날에는 장시간 야외활동을 줄이는 것을 고려합니다.
    • 실내에서 발생하는 연기와 먼지를 줄입니다.
    """
)


st.subheader("☀️ 오존(O₃)")

st.write(
    """
    오존 농도가 높은 경우에는 특히 햇빛이 강한 시간대의
    야외활동에 주의할 필요가 있습니다.

    • 오존 농도가 높은 시간대에는 장시간 야외활동을 줄입니다.
    • 실시간 오존 정보를 확인합니다.
    • 환기할 때 외부 대기질을 함께 확인합니다.
    """
)


st.subheader("🏭 이산화질소(NO₂)")

st.write(
    """
    NO₂는 자동차 배기가스나 연소 과정 등과 관련이 있는
    대기오염물질입니다.

    • 교통량이 많은 도로 주변의 대기질을 확인합니다.
    • 대기오염이 높은 시간대에는 불필요한 야외활동을 줄입니다.
    • 실내에서는 적절한 환기를 실시합니다.
    """
)


st.subheader("💨 일산화탄소(CO)")

st.write(
    """
    CO는 연료의 불완전 연소 과정에서 발생할 수 있는
    대기오염물질입니다.

    • 실내 연소기기의 적절한 사용과 환기에 주의합니다.
    • 연소기기를 사용하는 공간의 환기 상태를 확인합니다.
    • 이상이 있는 연소기기는 사용하지 않고 점검합니다.
    """
)


st.subheader("🏭 아황산가스(SO₂)")

st.write(
    """
    SO₂는 주로 연료의 연소 과정에서 발생할 수 있는
    대기오염물질입니다.

    • 대기질 정보를 확인합니다.
    • 농도가 높은 경우 장시간 야외활동을 줄이는 것을 고려합니다.
    • 실내 공기질도 함께 관리합니다.
    """
)


st.divider()


# -------------------------
# 상황별 대응 방법
# -------------------------

st.subheader("📌 상황별 대응 방법")

situation = st.selectbox(
    "현재 상황을 선택하세요.",
    [
        "미세먼지가 높은 경우",
        "오존이 높은 경우",
        "대기질이 전반적으로 양호한 경우"
    ]
)


if situation == "미세먼지가 높은 경우":

    st.warning(
        """
        🌫️ 미세먼지 농도가 높은 경우

        1. 실시간 대기질 정보를 확인합니다.
        2. 장시간 야외활동을 줄이는 것을 고려합니다.
        3. 외부 공기 상태를 확인하여 환기 시간을 조절합니다.
        4. 실내 먼지가 발생하지 않도록 관리합니다.
        """
    )


elif situation == "오존이 높은 경우":

    st.warning(
        """
        ☀️ 오존 농도가 높은 경우

        1. 오존 농도가 높은 시간대를 확인합니다.
        2. 해당 시간대의 장시간 야외활동을 줄이는 것을 고려합니다.
        3. 실외 대기질을 확인하면서 환기 시간을 조절합니다.
        """
    )


else:

    st.success(
        """
        🌱 현재 대기질이 비교적 양호한 경우

        1. 현재 상태를 지속적으로 확인합니다.
        2. 적절한 시간에 환기합니다.
        3. 실내 공기질도 함께 관리합니다.
        """
    )


st.divider()

st.caption(
    "※ AirCare의 대응 방법은 대기질 데이터를 바탕으로 한 일반적인 참고 정보입니다."
)
